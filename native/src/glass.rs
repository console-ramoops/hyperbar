/// Source uniform order: geo, rotation/texture scale, alpha/edge/thickness,
/// IOR/reflection/color power, glass color, inner color, dark/hit, directional
/// light, refraction/normal scale, intensity/luminance mix, luminance curve,
/// saturation/brightness, mask flag, curve mode, normal AA threshold.
/// `texture_scale` is supplied by the image-coordinate adapter; the ordinary
/// Root adapter encodes capture scale in its BitmapShader matrix and supplies1.
pub fn uniforms(token:&[f32;42],size:[f32;2],angle:f32,canvas_scale:f32,
    texture_scale:f32,sdf_scale:f32,mask:bool)->Option<[f32;51]>{
    if !token.iter().all(|v|v.is_finite())||!size.iter().all(|v|v.is_finite()&&*v>0.0)
        ||!angle.is_finite()||!canvas_scale.is_finite()||canvas_scale<=0.0
        ||!texture_scale.is_finite()||texture_scale<=0.0||!sdf_scale.is_finite()||sdf_scale<=0.0
        ||token[19]<=0.001{return None;}
    let mut out=[0.0;51];
    out[..4].copy_from_slice(&[0.0,0.0,size[0],size[1]]);
    let (sin,cos)=angle.sin_cos();
    out[4..8].copy_from_slice(&[cos,-sin,texture_scale,texture_scale]);
    out[8..12].copy_from_slice(&[token[18],token[19],token[21],token[22]]);
    out[12..16].copy_from_slice(&[token[32],token[24],token[23],token[17]]);
    out[16..20].copy_from_slice(&token[11..15]);
    out[20..24].copy_from_slice(&[token[15],token[16],token[33],token[34]]);
    out[24..28].copy_from_slice(&[token[8],token[9],token[7],0.0]);
    let x=token[25]*cos-token[26]*sin;let y=token[26]*cos+token[25]*sin;let z=token[27];
    let length=(x*x+y*y+z*z).sqrt();
    let direction=if length>0.0{[x/length,y/length,z/length]}
        else{[-0.3713909983634949,0.5570859909057617,-0.7427809834480286]};
    out[28..32].copy_from_slice(&[direction[0],direction[1],direction[2],token[30]*3.141590118408203_f32]);
    out[32..36].copy_from_slice(&[canvas_scale*(token[31]*0.8500000238418579_f32),
        if token[20]>0.001{1.0/token[20]}else{1.0},sdf_scale,sdf_scale]);
    out[36..40].copy_from_slice(&[token[28],token[29],token[10],token[4]]);
    // drawImage0xa47ad0 converts the token's four Bezier control points to
    // polynomial coefficients. Passing the raw controls is visibly different.
    let [a,b,c,d]=[token[0],token[1],token[2],token[3]];
    out[40..44].copy_from_slice(&[d-3.0*c+3.0*b-a,3.0*c-6.0*b+3.0*a,3.0*b-3.0*a,a]);
    out[44..48].copy_from_slice(&[token[5],token[6],token[35].max(1.0),token[36]]);
    out[48]=if mask{1.0}else{0.0};out[49]=0.0;
    // Native0xa47be0:2/max(edge,1e-4), not the older shader comment's3/edge.
    let t=(0.5+0.5*(2.0/token[19].max(0.0001)).min(1.0).sqrt()).clamp(0.0,1.0);
    out[50]=(t*t*t*(t*(t*6.0-15.0)+10.0)-0.5)*2.0;
    Some(out)
}

struct Cached<T>{key:NormalKey,value:T,bytes:usize}
/// Rust owns the original key/order/budget/context policy; the Android owner
/// retains actual floating-point GPU images and releases returned removals.
pub struct NormalCache<T>{
    entries:std::collections::VecDeque<Cached<T>>,
    bytes:usize,
    context:Option<u64>,
    max_entries:usize,
    max_bytes:usize,
}
impl<T> Default for NormalCache<T>{
    fn default()->Self{Self::with_limits(NORMAL_CACHE_ENTRIES,NORMAL_CACHE_BYTES)}
}
impl<T> NormalCache<T>{
    pub fn with_limits(max_entries:usize,max_bytes:usize)->Self{
        Self{entries:std::collections::VecDeque::new(),bytes:0,context:None,max_entries,max_bytes}
    }
    pub fn len(&self)->usize{self.entries.len()}
    pub fn bytes(&self)->usize{self.bytes}
    pub fn get(&mut self,key:NormalKey)->Option<&T>{
        let index=self.entries.iter().position(|entry|entry.key==key)?;
        let entry=self.entries.remove(index).unwrap();self.entries.push_front(entry);
        self.entries.front().map(|entry|&entry.value)
    }
    pub fn clear(&mut self)->Vec<(NormalKey,T)>{
        self.bytes=0;self.entries.drain(..).map(|entry|(entry.key,entry.value)).collect()
    }
    /// A null context does not discard native images. A different live
    /// recording context invalidates the complete original cache.
    pub fn use_context(&mut self,context:Option<u64>)->Vec<(NormalKey,T)>{
        if context.is_none()||context==self.context{return Vec::new();}
        self.context=context;self.clear()
    }
    /// Mirrors native pre-insertion eviction, including retention of one
    /// oversized image after the older cache has been emptied. Null image
    /// creation leaves existing entries untouched.
    pub fn put(&mut self,key:NormalKey,value:Option<T>,bytes:usize)->Vec<(NormalKey,T)>{
        let Some(value)=value else{return Vec::new();};let mut removed=Vec::new();
        if let Some(index)=self.entries.iter().position(|entry|entry.key==key){
            let entry=self.entries.remove(index).unwrap();self.bytes-=entry.bytes;removed.push((entry.key,entry.value));
        }
        while !self.entries.is_empty()&&(self.entries.len()>=self.max_entries||self.bytes.saturating_add(bytes)>self.max_bytes){
            let entry=self.entries.pop_back().unwrap();self.bytes-=entry.bytes;removed.push((entry.key,entry.value));
        }
        self.bytes=self.bytes.saturating_add(bytes);self.entries.push_front(Cached{key,value,bytes});removed
    }
}

fn smoothstep(a: f32, b: f32, x: f32) -> f32 {
    let t = ((x-a)/(b-a)).clamp(0.0,1.0);
    t*t*(3.0-2.0*t)
}
fn curve(x: f32, power: f32) -> f32 {
    if x >= 0.85 { return 1.0; }
    let t = (0.5+0.5*x.clamp(0.0,1.0).sqrt()).clamp(0.0,1.0);
    let t = t*t*t*(t*(t*6.0-15.0)+10.0);
    let t = (t-0.5)*2.0;
    1.0-(1.0-t).powf(power)
}

/// Actual source's unmixed supercircle SDF. Its directional fallback is not
/// used by the normal shader, which takes finite-difference derivatives.
fn supercircle_distance(offset: [f32;2], radius: f32) -> f32 {
    let scaled = 1.528_664_946_556_091_3_f32*radius.abs();
    let p = [(scaled+offset[0])/scaled,(scaled+offset[1])/scaled]
        .map(|v|v.max(0.0).abs());
    let largest=p[0].max(p[1]);
    let ratio=if largest==0.0 {0.0} else {(p[0].min(p[1])/largest).clamp(0.0,1.0)};
    let poly=(((-0.739_119_726_9_f32*ratio+2.403_492_764_8_f32)*ratio
        -2.490_731_917_3_f32)*ratio+0.476_870_896_0_f32)*ratio+0.474_784_759_4_f32;
    let length=(p[0]*p[0]+p[1]*p[1]).sqrt();
    let distance=(length+1.0)-1.0/(1.0-ratio*ratio*length.clamp(0.0,1.0)*poly);
    let radial=[scaled+offset[0],scaled+offset[1]];
    radial[0].max(radial[1]).min(0.0)+scaled*(distance-1.0)
}

fn sdf(point: [f32;2], radius: f32, edge: f32, power: f32, circle: bool) -> f32 {
    let offset=[-point[0],-point[1]];
    let d=if circle {
        ((radius+offset[0]).powi(2)+(radius+offset[1]).powi(2)).sqrt()-radius
    } else {supercircle_distance(offset,radius)};
    if d < -edge {-edge} else if d < 0.0 {-curve(-d/edge,power)*edge} else {d}
}

/// Source's encoded normal.xy and normalized edge distance, before its half
/// storage and corner-mask lookup. `xy` is a corner-local pixel coordinate.
pub fn normal(point: [f32;2], radius: f32, edge: f32, power: f32, circle: bool) -> Option<[f32;3]> {
    if !point.into_iter().all(f32::is_finite) || NormalKey::new(circle,radius,edge,power).is_none() {
        return None;
    }
    let d=sdf(point,radius,edge,power,circle);
    let mut n=[0.0,0.0];
    if d > -edge {
        let eps=0.001_f32;
        let right=sdf([point[0]+eps,point[1]],radius,edge,power,circle);
        let left=sdf([point[0]-eps,point[1]],radius,edge,power,circle);
        let top=sdf([point[0],point[1]+eps],radius,edge,power,circle);
        let bottom=sdf([point[0],point[1]-eps],radius,edge,power,circle);
        let x=(right-left)/(eps*2.0);let y=(top-bottom)/(eps*2.0);
        let length=(x*x+y*y+1.0).sqrt();
        n=[x/length,y/length];
    }
    n[0]*=1.0-smoothstep(radius-3.0,radius-1.0,point[0]);
    n[1]*=1.0-smoothstep(radius-3.0,radius-1.0,point[1]);
    Some([n[0]*0.5+0.5,n[1]*0.5+0.5,-d/edge])
}

