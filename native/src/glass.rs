//! Xiaomi glass quarter-normal geometry from the shipped libhwui shader at
//! file offset 0xc0bf9. Cache packing follows drawImage 0xa4763c..0xa47670;
//! radius rounds to an integer, edge to tenths, exponent to hundredths.
//! Texture composition remains a separate Android GPU boundary.

#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]
pub struct NormalKey {
    pub circle: bool,
    pub radius: i32,
    pub edge_tenths: i32,
    pub power_hundredths: i32,
}

impl NormalKey {
    pub fn new(circle: bool, radius: f32, edge: f32, power: f32) -> Option<Self> {
        if !radius.is_finite() || !edge.is_finite() || !power.is_finite()
            || radius <= 0.0 || edge <= 0.0 || power <= 0.0
            || radius > 16384.0 || edge > 16384.0 || power > 100.0 {
            return None;
        }
        // ARM FCVTAS is nearest, with halfway cases away from zero. These
        // positive values preserve the source f32 multiply before conversion.
        let key = Self {
            circle,
            radius: radius.round() as i32,
            edge_tenths: (edge * 10.0).round() as i32,
            power_hundredths: (power * 100.0).round() as i32,
        };
        (key.radius > 0 && key.edge_tenths > 0 && key.power_hundredths > 0).then_some(key)
    }
    pub fn packed(self) -> [u64; 2] {
        [u64::from(self.circle) | ((self.radius as u32 as u64) << 32),
         self.edge_tenths as u32 as u64 | ((self.power_hundredths as u32 as u64) << 32)]
    }
    pub fn parameters(self) -> [f32; 3] {
        [self.radius as f32, self.edge_tenths as f32 / 10.0,
         self.power_hundredths as f32 / 100.0]
    }
    /// findNormalImage allocates an R+3 square quarter-image at0xa499d8.
    pub fn quarter_side(self) -> usize { self.radius as usize + 3 }
}

/// Source normal-image cache limits at libhwui file offset0x35320.
pub const NORMAL_CACHE_ENTRIES:usize=20;
pub const NORMAL_CACHE_BYTES:usize=50*1024*1024;
pub const CORNER_MIP_SIDES:[usize;10]=[512,256,128,64,32,16,8,4,2,1];
pub const CORNER_MIP_PIXELS:usize=349525;
/// The original asset is a headerless, contiguous RGBA8 mip chain. Preserve
/// every supplied level; its masks differ from autogenerated box-filter mips.
pub fn decode_corner_mips(rgba:&[u8])->Option<Vec<u32>>{
    if rgba.len()!=CORNER_MIP_PIXELS*4{return None;}
    Some(rgba.chunks_exact(4).map(|p|((p[3] as u32)<<24)|((p[0] as u32)<<16)|((p[1] as u32)<<8)|p[2] as u32).collect())
}

